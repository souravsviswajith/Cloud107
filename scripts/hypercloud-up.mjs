#!/usr/bin/env node
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { setTimeout as delay } from 'node:timers/promises';

const root = process.cwd();
const envPath = `${root}/.env`;
const composePath = `${root}/docker-compose.yml`;
const manifestPath = `${root}/hypercloud/workloads/cloud107.json`;

function fail(message) {
  console.error(`[hypercloud] ERROR: ${message}`);
  process.exit(1);
}

if (!existsSync(composePath) || !existsSync(manifestPath)) {
  fail('Run this command from the HyperCloud107 repository root.');
}

let manifest;
try {
  manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
} catch (error) {
  fail(`Invalid workload manifest: ${error.message}`);
}
if (
  manifest.apiVersion !== 'hypercloud.107/v1alpha1' ||
  manifest.kind !== 'Workload' ||
  manifest.spec?.runtime?.adapter !== 'docker-compose' ||
  !Array.isArray(manifest.spec?.runtime?.services)
) {
  fail('Workload manifest does not satisfy the first-slice contract.');
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: root,
    stdio: 'inherit',
    shell: process.platform === 'win32',
    ...options,
  });
  if (result.error) fail(result.error.message);
  if (result.status !== 0) fail(`Command failed: ${command} ${args.join(' ')}`);
}

if (!existsSync(envPath)) {
  const databasePassword = randomBytes(32).toString('base64url');
  const generated = [
    '# Generated by HyperCloud first-slice launcher. Keep this file private.',
    'SQL_ADMIN_USER=postgres',
    `SQL_ADMIN_PASSWORD=${databasePassword}`,
    'SQL_USER=postgres',
    `SQL_PASSWORD=${databasePassword}`,
    'SQL_DB_NAME=cloud107',
    `C107_AUTH_SECRET=${randomBytes(48).toString('base64url')}`,
    'APP_URL=http://localhost:3000',
    '',
  ].join('\n');
  writeFileSync(envPath, generated, { flag: 'wx', mode: 0o600 });
  console.log('[hypercloud] Created private .env with locally generated secrets.');
} else {
  const env = readFileSync(envPath, 'utf8');
  const required = ['SQL_ADMIN_PASSWORD', 'SQL_PASSWORD', 'C107_AUTH_SECRET'];
  const missing = required.filter((key) => {
    const match = env.match(new RegExp(`^\\s*${key}\\s*=\\s*(.*?)\\s*$`, 'm'));
    return !match || !match[1] || /^(change-this|replace-with-a-long-random-secret)$/i.test(match[1].replace(/^["']|["']$/g, ''));
  });
  if (missing.length) {
    fail(`Set non-empty, non-placeholder values in .env: ${missing.join(', ')}. Existing .env was not modified.`);
  }
}

console.log('[hypercloud] Validating Compose configuration...');
run('docker', ['compose', 'config', '--quiet']);
console.log('[hypercloud] Building and starting the Cloud107 workload slice...');
run('docker', ['compose', 'up', '--build', '-d']);

const url = manifest.spec.entrypoint.localUrl;
let lastError = 'No response';
for (let attempt = 1; attempt <= 30; attempt += 1) {
  try {
    const response = await fetch(url, { signal: AbortSignal.timeout(3000) });
    if (response.ok) {
      console.log(`[hypercloud] Workload endpoint responded with HTTP ${response.status}: ${url}`);
      run('docker', ['compose', 'ps']);
      console.log('[hypercloud] First slice is reachable. This verifies local startup only, not production readiness.');
      process.exit(0);
    }
    lastError = `HTTP ${response.status}`;
  } catch (error) {
    lastError = error.message;
  }
  await delay(2000);
}
console.error(`[hypercloud] Endpoint did not become reachable: ${lastError}`);
console.error('[hypercloud] Inspect logs with: docker compose logs --tail=200 cloud107');
process.exit(1);
